export const jobsBySlug = Object.fromEntries(jobs.map((j) => [j.slug, j]));
export const jobsById = Object.fromEntries(jobs.map((j) => [j.id, j]));

export const getJobBySlug = (slug) => jobsBySlug[slug] ?? null;

export const getAdjacentJobs = (slug) => {
    const idx = jobs.findIndex((j) => j.slug === slug);
    if (idx < 0) return {prev: null, next: null};
    const prev = idx > 0 ? jobs[idx - 1] : jobs[jobs.length - 1];
    const next = idx < jobs.length - 1 ? jobs[idx + 1] : jobs[0];
    return {prev, next};
};
